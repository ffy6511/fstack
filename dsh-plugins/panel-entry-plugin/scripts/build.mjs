import { existsSync, readdirSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const sibling = resolve(root, '../openui-blocks-plugin/node_modules/.pnpm');
let esbuild = join(root, 'node_modules/esbuild/bin/esbuild');
if (!existsSync(esbuild)) {
  const hit =
    existsSync(sibling) && readdirSync(sibling).find((name) => name.startsWith('esbuild@'));
  esbuild = hit ? join(sibling, hit, 'node_modules/esbuild/bin/esbuild') : 'esbuild';
}
const compiled = spawnSync(
  esbuild,
  [
    join(root, 'src/client.tsx'),
    '--bundle',
    '--format=cjs',
    '--platform=browser',
    '--target=es2022',
    '--external:react',
    '--external:@deepseek-ai/dsh-client-ui-primitives',
  ],
  { encoding: 'utf8', maxBuffer: 4 * 1024 * 1024 },
);
if (compiled.status !== 0)
  throw new Error(compiled.stderr || 'Install dev dependencies with npm install');
const css = await readFile(join(root, 'src/client.css'), 'utf8');
const body = compiled.stdout.replace(/['"]__PANEL_CSS__['"]/, () => JSON.stringify(css));
const bundle = `/* Generated by scripts/build.mjs; edit src/client.tsx instead. */
window.__ModuleLoader__.load({
  id: '@fstack/dsh-panel-entry',
  factory: (require) => {
    const module = { exports: {} };
    (function(module, exports, require) {
${body}
    })(module, module.exports, require);
    return module.exports.default ?? module.exports;
  },
});
`;
await writeFile(join(root, 'client.js'), bundle);
console.log(`client.js (${(bundle.length / 1024).toFixed(1)} kB)`);
