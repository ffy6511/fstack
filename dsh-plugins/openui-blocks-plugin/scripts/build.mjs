/**
 * Build the shipped client bundle and (with --preview) the local preview page.
 *
 * The client bundle is NOT a plain ESM file: the harness's browser module
 * loader registers plugin code as a CJS factory (`window.__ModuleLoader__`),
 * and `react` / `react/jsx-runtime` resolve through the loader's own table.
 * So esbuild emits CommonJS with React external, and the wrapper below hands it
 * the loader's `require`.
 */

import { build } from 'esbuild';
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const preview = process.argv.includes('--preview');

/**
 * @param {import('esbuild').BuildOptions} options
 */
async function run(options) {
  await build({ absWorkingDir: root, logLevel: 'warning', ...options });
}

async function buildClient() {
  const outfile = resolve(root, '.build/client.cjs');
  await mkdir(dirname(outfile), { recursive: true });
  await run({
    entryPoints: ['src/client/index.jsx'],
    outfile,
    bundle: true,
    format: 'cjs',
    platform: 'browser',
    target: ['es2022'],
    jsx: 'automatic',
    external: ['react', 'react/jsx-runtime'],
    legalComments: 'none',
  });
  const body = await readFile(outfile, 'utf8');
  const wrapped = [
    '/* @fstack/dsh-openui-blocks — generated by scripts/build.mjs; edit src/client instead. */',
    "window.__ModuleLoader__.load({",
    "  id: '@fstack/dsh-openui-blocks',",
    '  factory: (require) => {',
    '    const module = { exports: {} };',
    '    (function (module, exports, require) {',
    body,
    '    })(module, module.exports, require);',
    '    return module.exports.default ?? module.exports;',
    '  },',
    '});',
    '',
  ].join('\n');
  await writeFile(resolve(root, 'client.js'), wrapped, 'utf8');
  return wrapped.length;
}

async function buildPreview() {
  await run({
    entryPoints: ['preview/main.jsx'],
    outfile: 'preview/bundle.js',
    bundle: true,
    format: 'iife',
    platform: 'browser',
    target: ['es2022'],
    jsx: 'automatic',
    loader: { '.js': 'jsx' },
    define: { 'process.env.NODE_ENV': '"production"' },
  });
}

if (preview) {
  await buildPreview();
  console.log('preview/bundle.js');
} else {
  const bytes = await buildClient();
  console.log(`client.js (${(bytes / 1024).toFixed(1)} kB)`);
}
