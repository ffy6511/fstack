import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import vm from 'node:vm';

test('tracking table renders chronological baseline and stages in fixed aligned columns', async () => {
  let plugin;
  const h = (type, props, ...children) => typeof type === 'function' ? type({ ...props, children }) : ({ type, props: props || {}, children: children.flat() });
  const icons = new Proxy({}, { get: (_target, name) => props => h(name === 'Tooltip' ? 'tooltip' : name === 'Button' ? 'button' : name === 'Checkbox' ? 'checkbox' : name === 'Switch' ? 'switch' : 'svg', props, ...(props.children || [])) });
  const window = { __ModuleLoader__: { load({ factory }) { plugin = factory(name => name === 'react' ? { createElement: h } : icons); } } };
  vm.runInNewContext((await readFile(new URL('../client.js', import.meta.url), 'utf8')).replace('return module.exports.default ?? module.exports;', 'return module.exports;'), { window });
  const row = { pass: 2, fail: 1, error: 0, passRate: 2/3, finished: 3, expected: 3 };
  const first = { id: 'stage-one', at: '2026-01-01T00:00:00Z', label: '首次观测', row, revision: null, delta: null };
  const second = { ...first, id: 'stage-two', at: '2026-01-01T00:05:00Z', label: '阶段二', row: { ...row, pass: 3, fail: 0 }, delta: { comparable: true, pass: 1, fail: -1, error: 0 } };
  const run = { id: 'one', title: 'Experiment', source: { kind: 'local', path: '/data' }, stages: [first, second], latest: second, refreshSeconds: 60 };
  let chosen;
  const props = { runs: [run], selectedIds: [], onToggle: id => { chosen = id; }, onRefresh() {}, onArchive() {}, onOpen() {}, onStage() {}, setLabel() {}, onCheckpoint() {} };
  const table = plugin.TrackingTable(props); assert.equal(table.type, 'table'); assert.equal(table.children[0].children.length, 7);
  const body = table.children[1];
  body.children = body.children.filter(Boolean);
  const floating = body.children[0].children[6].children[0];
  assert.equal(floating.props.className, 'ageval-floating-actions');
  assert.equal(floating.children[0].children[0].children[0].type, 'switch');
  assert.ok(!JSON.stringify(floating).includes('删除'));
  assert.equal(body.children[0].children[1].children.length, 1);
  assert.equal(body.children[0].children[1].props.colSpan, undefined);
  const css = await readFile(new URL('../src/client.css', import.meta.url), 'utf8');
  assert.match(css, /\.ageval-tracking-table \.ageval-table-actions \{\s*position: sticky;\s*right: 0/s);
  assert.match(css, /\.ageval-tracking-scroll \{[\s\S]*padding: 0 0 12px;/);
  assert.match(css, /\.ageval-col-actions \{\s*width: 44px;/);
  assert.match(css, /ageval-tracking-stage-row:hover \.ageval-stage-actions/);
  assert.equal(body.children[1].children[1].children[0].children[0], '首次观测');
  assert.equal(body.children[2].children[1].children[0].children[0], '阶段二');
  assert.equal(body.children[2].children[4].children[0], '+1 / -1 / +0');
  assert.equal(body.children[2].children[6].children[0].children[0].props.label, '删除这次采样记录');
  assert.equal(body.children.filter(n => n?.props?.className === 'ageval-tracking-stage-row').length, 2);
  body.children[0].children[0].children[0].props.onChange(); assert.equal(chosen, 'one');
  const latest = { ...second, row: { ...row, pass: 4 } };
  const current = plugin.TrackingTable({ ...props, runs: [{ ...run, latest }] });
  assert.equal(current.children[1].children.filter(Boolean)[3].children[1].children[0].children[0], '当前观测');
  const action = plugin.ActionIcon({ glyph: icons.IconClockOutlineRegular, label: '追踪中' });
  assert.equal(action.type, 'tooltip'); assert.equal(action.props.label, '追踪中'); assert.equal(action.children[0].props['aria-label'], '追踪中');
});
