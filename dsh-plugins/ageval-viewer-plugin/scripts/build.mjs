import { existsSync, readdirSync } from 'node:fs';
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { spawnSync } from 'node:child_process';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

function findEsbuild() {
  const local = join(root, 'node_modules/esbuild/bin/esbuild');
  if (existsSync(local)) return local;
  const sibling = resolve(root, '../openui-blocks-plugin/node_modules/.pnpm');
  if (existsSync(sibling)) {
    const hit = readdirSync(sibling).find(name => name.startsWith('esbuild@'));
    if (hit) {
      const bin = join(sibling, hit, 'node_modules/esbuild/bin/esbuild');
      if (existsSync(bin)) return bin;
    }
  }
  return 'esbuild';
}

const esbuild = findEsbuild();
const outfile = join(root, '.build/client.js');
await mkdir(dirname(outfile), { recursive: true });
const compiled = spawnSync(esbuild, [
  join(root, 'src/client.tsx'),
  '--bundle',
  '--format=cjs',
  '--platform=browser',
  '--target=es2022',
  '--external:react',
  '--outfile=' + outfile,
], { stdio: 'inherit' });
if (compiled.status) process.exit(compiled.status ?? 1);

let body = await readFile(outfile, 'utf8');
const css = await readFile(join(root, 'src/client.css'), 'utf8');
if (!body.includes('__AGEVAL_CSS__')) throw new Error('CSS marker missing from compiled client');
body = body.replace(/['"]__AGEVAL_CSS__['"]/, () => JSON.stringify(css));

const wrapped = [
  '/* @fstack/dsh-ageval-viewer — generated by scripts/build.mjs; edit src/client.tsx instead. */',
  'window.__ModuleLoader__.load({',
  "  id: '@fstack/dsh-ageval-viewer',",
  '  factory: (require) => {',
  '    const module = { exports: {} };',
  '    (function (module, exports, require) {',
  body,
  '    })(module, module.exports, require);',
  '    return module.exports.default ?? module.exports;',
  '  },',
  '});',
  '',
].join('\n');
await writeFile(join(root, 'client.js'), wrapped);
console.log('client.js (' + (wrapped.length / 1024).toFixed(1) + ' kB)');
